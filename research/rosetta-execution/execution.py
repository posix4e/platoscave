#!/usr/bin/env python3
"""Durable, serial-by-default execution of the complete two-study fit schedule.

This stdlib controller never imports a model, torch, or a fitting API. `tick`
reconciles retained systemd user services, then makes at most one admission
batch. `run` repeats ticks every 30 seconds. Controller/SSH death does not restart scientific work.
Both fit and strict-reader services use the same retained, no-restart recipe.
There is no kill, timeout, automatic retry, unit cleanup, or score selection.

An externally reviewed final execution lock must have schema_version=1,
status=frozen_before_control_execution, studies.model/source with protocol and
input logical file keys, schedule='schedule', resources='resources', code keys
model_runner/model_reader/source_runner/source_reader, files mapping logical
keys to SHA256, environment (explicit env -i values), and failure_policy=
stop_on_any_failure. It binds this file under code.launcher; code.dependencies
is a list of every other scientific helper's logical file key. Required code
closure is checked against both protocols. The resource JSON declares max_jobs
(1 or prospectively amended 2), a class for every job ('shared'/'exclusive'),
an external_work_quiescent_receipt logical key, and, for 2, amendment logical
key. Both receipts must have status='approved_before_execution'. The source
budget must have status='frozen_before_source_control_masks_and_fits'.

Private immutable bindings contain files (same logical keys -> absolute paths),
python, cwd, registry_root, control_root, model/source (runner_bindings file,
attempts_root, private_trace_root). Those runner binding files are themselves
logical files model_bindings/source_bindings in the lock. A fixed per-UID systemd runtime registry also enforces the
single shared admission lock across differently configured private roots. Its
immutable owner prevents another execution silently using this resource budget.
A separate prior-work receipt is required; it is not a live process detector.

All tickets, logs, identities, reader outputs and replay-binding snapshots are
outside both runner-owned directories. Existing outputs, missing units after a
dispatch intent, changed InvocationIDs, boot changes, partial/conflicting
markers and failed verification block dispatch. Immutable records retain every
outcome. A reviewer-supplied retry can be dispatched explicitly with `retry`;
predecessor quiescence and exact review hashes are checked before launch.

No release or scientific input is generated by this program. `schedule` writes
only the complete proposed schedule from supplied protocols/masks and is not
authorization to fit. `validate` checks the final release without dispatch.
"""
from __future__ import annotations
import argparse
from contextlib import contextmanager
from datetime import datetime, timezone
import fcntl
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import time
import uuid

SEEDS = [734796314, 576165995, 2197670066, 839703249, 2584932063]
VISION = ['dinov2', 'dino', 'moco', 'mae']
TEXT = ['mpnet', 'glove', 'elmo']
METHODS = ['rosetta', 'orthogonal_paired', 'orthogonal_shuffled', 'linear_paired', 'linear_shuffled']
PROPERTIES = {'Type': 'exec', 'ExitType': 'cgroup', 'RemainAfterExit': 'yes', 'Restart': 'no',
              'RuntimeMaxSec': 'infinity', 'TimeoutStartSec': 'infinity', 'TimeoutStopSec': 'infinity'}
SHOW_PROPERTIES = {'Type': 'exec', 'ExitType': 'cgroup', 'RemainAfterExit': 'yes', 'Restart': 'no',
                   'RuntimeMaxUSec': 'infinity', 'TimeoutStartUSec': 'infinity', 'TimeoutStopUSec': 'infinity', 'NRestarts': '0'}
PARTIALS = ('COMPLETE.json.partial', 'FAILED.json.partial')
SHA = re.compile(r'^[0-9a-f]{64}$')


class Blocked(RuntimeError):
    pass


def need(condition, message):
    if not condition:
        raise Blocked(message)


def digest(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def encoded(value):
    return (json.dumps(value, sort_keys=True, indent=2, allow_nan=False) + '\n').encode()


def object_hash(value):
    return hashlib.sha256(encoded(value)).hexdigest()


def read(path):
    return json.loads(Path(path).read_text())


def sync_dir(path):
    fd = os.open(path, os.O_RDONLY)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)


def ensure_dir(path):
    path = Path(path)
    absent = []; cursor = path
    while not cursor.exists():
        absent.append(cursor); cursor = cursor.parent
    need(cursor.is_dir(), 'Metadata parent is not a directory')
    for directory in reversed(absent):
        directory.mkdir(); sync_dir(directory.parent)
    need(path.is_dir(), 'Metadata path is not a directory')


def write_new(path, value):
    """An interrupted write remains evidence, never a silently replaceable file."""
    path = Path(path)
    ensure_dir(path.parent)
    with path.open('xb') as stream:
        stream.write(encoded(value)); stream.flush(); os.fsync(stream.fileno())
    sync_dir(path.parent)


def write_or_check(path, value):
    if Path(path).exists():
        need(Path(path).read_bytes() == encoded(value), f'Immutable record differs: {Path(path).name}')
    else:
        write_new(path, value)


def stamp():
    return datetime.now(timezone.utc).isoformat()


def absolute(path):
    p = Path(path)
    need(p.is_absolute(), 'Private paths must be absolute')
    return p.resolve()


def separated(paths):
    for i, p in enumerate(paths):
        for q in paths[i + 1:]:
            need(not p.is_relative_to(q) and not q.is_relative_to(p), 'Control/attempt/trace roots overlap')


def derive_schedule(model, source, masks):
    need(model['seeds'] == source['seeds'] == SEEDS, 'Original five-seed order changed')
    need(model['vision_models'] == VISION and model['text_models'] == TEXT and model['methods'] == METHODS,
         'Complete model panel changed')
    pairs = [('dinov2', 'mpnet')] + [(v, t) for v in VISION for t in TEXT if (v, t) != ('dinov2', 'mpnet')]
    names = ['O', 'C', 'D']
    for family in ('Rv', 'Rp'):
        seeds = source['selection_seeds'][family]
        need(bool(seeds) and len(set(seeds)) == len(seeds) and all(type(s) is int and s >= 0 for s in seeds), 'Invalid declared mask seeds')
        names += [f'{family}-{s}' for s in seeds]
    need(set(masks['masks']) == set(names), 'Mask bundle omits or adds declared masks')
    jobs = []
    for v, t in pairs:
        for seed in SEEDS:
            jobs.append({'study': 'model', 'vision': v, 'text': t, 'seed': seed,
                         'stage': 'replay' if (v, t) == ('dinov2', 'mpnet') else 'expanded',
                         'key': f'{v}/{t}/{seed}', 'id': f'model-{v}-{t}-{seed}'})
    for mask in names:
        for seed in SEEDS:
            jobs.append({'study': 'source', 'mask': mask, 'seed': seed, 'stage': 'source',
                         'mask_sha256': masks['masks'][mask]['mask_sha256'],
                         'key': f'{mask}/{seed}', 'id': f'source-{mask}-{seed}'})
    return {'schema_version': 1, 'order': 'model_reference_then_panel_then_declared_source_masks',
            'jobs': [dict(index=i, **job) for i, job in enumerate(jobs)]}


class Release:
    def __init__(self, lock_path, expected, bindings_path, bindings_sha):
        self.lock_path, self.bindings_path = absolute(lock_path), absolute(bindings_path)
        need(digest(self.lock_path) == expected and digest(self.bindings_path) == bindings_sha, 'Outer lock/binding hash differs')
        self.sha, self.bindings_sha = expected, bindings_sha
        self.lock, self.bindings = read(self.lock_path), read(self.bindings_path)
        l, b = self.lock, self.bindings
        need(l.get('schema_version') == 1 and l.get('status') == 'frozen_before_control_execution', 'Execution lock is not final')
        need(l.get('failure_policy') == 'stop_on_any_failure' and l.get('systemd_properties') == PROPERTIES, 'Unsupported execution policy/recipe')
        need(set(b['files']) == set(l['files']) and all(SHA.fullmatch(h) for h in l['files'].values()), 'File closure differs')
        self.files = {name: absolute(path) for name, path in b['files'].items()}
        self.recheck()
        need(self.files[l['code']['launcher']] == Path(__file__).resolve(), 'Run the locked launcher source')
        self.python, self.cwd = absolute(b['python']), absolute(b['cwd'])
        need(self.python.is_file() and self.cwd.is_dir(), 'Missing exact runtime or working directory')
        self.root, self.registry = absolute(b['control_root']), absolute(b['registry_root'])
        roots = [self.root]
        for study in ('model', 'source'):
            roots += [absolute(b[study]['attempts_root']), absolute(b[study]['private_trace_root'])]
            need(absolute(b[study]['runner_bindings']) == self.files[f'{study}_bindings'], 'Runner binding snapshot is not bound')
            rb = read(b[study]['runner_bindings'])
            need(absolute(rb['python_executable']) == self.python and absolute(rb['source_root']) == self.cwd, 'Runtime/source path disagreement')
        separated(roots)
        need(not any(self.registry.is_relative_to(p) for p in roots[1:]), 'Registry inside runner output')
        self.model = self.document(l['studies']['model']['protocol'])
        self.source = self.document(l['studies']['source']['protocol'])
        self.features = self.document(l['studies']['model']['input'])
        self.masks = self.document(l['studies']['source']['input'])
        need(self.model['status'] == 'frozen_before_model_control_fits' and
             self.source['status'] == 'frozen_before_source_control_fits', 'Scientific protocols are not final')
        need(self.source['research_design']['budget']['status'] == 'frozen_before_source_control_masks_and_fits', 'Source budget not final')
        need(self.features['status'] == 'frozen_before_model_control_fits' and len(self.features['features']) == 14 and
             self.features['protocol_sha256'] == self.hash_for('model', 'protocol'), 'Feature lock not complete/bound')
        need(self.masks['protocol_sha256'] == self.hash_for('source', 'protocol'), 'Masks refer to another protocol')
        self.schedule = self.document(l['schedule'])
        need(self.schedule == derive_schedule(self.model, self.source, self.masks), 'Schedule omits/reorders/adds jobs')
        need(self.source['research_design']['budget']['fits'] == len(self.schedule['jobs']) - 60, 'Source budget count differs')
        self.resources = self.document(l['resources'])
        r = self.resources
        need(r['max_jobs'] in (1, 2) and type(r['max_jobs']) is int, 'Unsupported concurrency')
        need(set(r['classes']) == {j['id'] for j in self.schedule['jobs']} and
             set(r['classes'].values()) <= {'shared', 'exclusive'}, 'Incomplete resource class table')
        need(self.document(r['external_work_quiescent_receipt']).get('status') == 'approved_before_execution', 'Prior work not cleared')
        if r['max_jobs'] == 2:
            need(self.document(r['amendment']).get('status') == 'approved_before_execution', 'Concurrency amendment not approved')
        environment = l['environment']
        need(isinstance(environment, dict) and environment.get('ATEN_CPU_CAPABILITY') == 'avx2' and
             environment.get('MKL_CBWR') == 'AVX2,STRICT' and environment.get('PYTHONNOUSERSITE') == '1' and not ({'PYTHONPATH', 'PYTHONHOME'} & set(environment)), 'Unsafe or unpinned environment')
        allowed_env = {'ATEN_CPU_CAPABILITY', 'MKL_CBWR', 'PYTHONNOUSERSITE', 'OMP_NUM_THREADS', 'MKL_NUM_THREADS',
                       'OPENBLAS_NUM_THREADS', 'NUMEXPR_NUM_THREADS', 'OMP_DYNAMIC', 'MKL_DYNAMIC', 'MALLOC_ARENA_MAX',
                       'PYTHONHASHSEED', 'LANG', 'LC_ALL'}
        need(set(environment) <= allowed_env and all(isinstance(v, str) and re.fullmatch(r'[A-Za-z0-9_,.:+\-]*', v) for v in environment.values()),
             'Public environment must contain only explicit path-free runtime settings')
        closure = {l['code'][k] for k in ('launcher', 'model_runner', 'model_reader', 'source_runner', 'source_reader')}
        closure.update(l['code']['dependencies'])
        for p, reader in ((self.model, 'model_reader'), (self.source, 'source_reader')):
            for filename, sha in p['code_sha256'].items():
                need(any(self.files[k].name == filename and l['files'][k] == sha for k in closure), f'Code closure missing {filename}')
            reporting = p['research_design']['reporting']
            # Reporting records currently expose summarizer_sha256; also require
            # the outer lock's exact reader bytes irrespective of metadata layout.
            metadata = reporting['summarizer' if reader == 'model_reader' else 'implementation']
            need(metadata['sha256'] == l['files'][l['code'][reader]], 'Reader differs from scientific protocol')
        self.recheck()

    def document(self, key):
        return read(self.files[key])

    def hash_for(self, study, field):
        return self.lock['files'][self.lock['studies'][study][field]]

    def path_for(self, study, field):
        return str(self.files[self.lock['studies'][study][field]])

    def recheck(self):
        need(digest(self.lock_path) == self.sha and digest(self.bindings_path) == self.bindings_sha, 'Outer bytes changed')
        for name, path in self.files.items() if hasattr(self, 'files') else []:
            need(digest(path) == self.lock['files'][name], f'Bound file changed: {name}')

    def command(self, script, arguments):
        return ['/usr/bin/env', '-i', *[f'{k}={v}' for k, v in sorted(self.lock['environment'].items())],
                str(self.python), str(self.files[self.lock['code'][script]]), *map(str, arguments)]


def runtime_registry():
    """One fixed admission namespace per Linux user, across private bindings."""
    return Path('/run/user') / str(os.getuid()) / 'rosetta-execution'


@contextmanager
def controller_lock(release):
    global_root = runtime_registry()
    need(global_root.parent.is_dir(), 'Systemd user runtime directory is absent')
    ensure_dir(global_root)
    with (global_root / 'controller.lock').open('a+') as stream:
        try:
            fcntl.flock(stream, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as error:
            raise Blocked('Another controller holds the global user resource registry') from error
        owner = {'execution_sha256': release.sha, 'bindings_sha256': release.bindings_sha, 'control_root': str(release.root)}
        write_or_check(global_root / 'owner.json', owner)
        ensure_dir(release.registry)
        write_or_check(release.registry / 'owner.json', owner)
        yield


def run(argv):
    return subprocess.run(argv, check=True, text=True, capture_output=True).stdout


class Systemd:
    """A retained transient unit is the atomic dispatch identity; never reuse it."""
    def gate(self):
        need(os.name == 'posix' and Path('/proc/sys/kernel/random/boot_id').exists(), 'Linux cgroup host required')
        need(run(['loginctl', 'show-user', str(os.getuid()), '--property=Linger', '--value']).strip() == 'yes', 'User linger must be enabled')
        need(Path('/sys/fs/cgroup/cgroup.controllers').exists(), 'Unified cgroup v2 required')

    def launch(self, ticket):
        self.gate()
        args = ['systemd-run', '--user', '--quiet', '--unit=' + ticket['unit'], '--description=rosetta-ticket-' + object_hash(ticket),
                '--working-directory=' + ticket['cwd']]
        args += ['--property=' + k + '=' + v for k, v in PROPERTIES.items()]
        args += ['--property=StandardOutput=append:' + ticket['stdout'], '--property=StandardError=append:' + ticket['stderr']]
        run([*args, '--', *ticket['argv']])

    def inspect(self, ticket):
        raw = run(['systemctl', '--user', 'show', ticket['unit'], '--no-pager'])
        fields = dict(line.split('=', 1) for line in raw.splitlines() if '=' in line)
        need(fields.get('LoadState') == 'loaded', 'Dispatched unit is absent/unloaded')
        for key, value in SHOW_PROPERTIES.items():
            need(fields.get(key) == value, 'Systemd recipe differs: ' + key)
        need(fields.get('Description') == 'rosetta-ticket-' + object_hash(ticket), 'Unit ticket hash differs')
        need(fields.get('WorkingDirectory') == ticket['cwd'], 'Unit working directory differs')
        obj = json.loads(run(['busctl', '--user', '--json=short', 'call', 'org.freedesktop.systemd1', '/org/freedesktop/systemd1',
                              'org.freedesktop.systemd1.Manager', 'GetUnit', 's', ticket['unit']]))['data'][0]
        start = json.loads(run(['busctl', '--user', '--json=short', 'get-property', 'org.freedesktop.systemd1', obj,
                                'org.freedesktop.systemd1.Service', 'ExecStart']))['data']
        need(len(start) == 1 and start[0][0] == ticket['argv'][0] and start[0][1] == ticket['argv'], 'Unit command differs')
        need(re.fullmatch('[0-9a-f]{32}', fields.get('InvocationID', '')) is not None, 'Missing invocation identity')
        pid = int(fields['MainPID'])
        ticks = None
        if pid:
            try:
                ticks = int(Path(f'/proc/{pid}/stat').read_text().rsplit(')', 1)[1].split()[19])
            except FileNotFoundError:
                pass  # InvocationID+cgroup remain authoritative during PID exit.
        return {'invocation_id': fields['InvocationID'], 'boot_id': Path('/proc/sys/kernel/random/boot_id').read_text().strip(),
                'cgroup': fields.get('ControlGroup', ''), 'main_pid': pid, 'starttime_ticks': ticks,
                'active': fields['ActiveState'], 'sub': fields['SubState'], 'result': fields['Result'],
                'exec_code': fields['ExecMainCode'], 'exec_status': fields['ExecMainStatus']}

    def populated(self, group):
        need(group.startswith('/') and '..' not in Path(group).parts, 'Invalid systemd cgroup path')
        path = Path('/sys/fs/cgroup') / group.lstrip('/')
        if not path.exists():
            return False
        values = dict(line.split() for line in (path / 'cgroup.events').read_text().splitlines())
        need('populated' in values, 'Cgroup population unavailable')
        return values['populated'] != '0'


def reconcile_service(directory, backend):
    ticket = read(directory / 'ticket.json')
    need((directory / 'dispatch.json').exists(), 'Ticket lacks durable dispatch intent; manual resolution required')
    need(read(directory / 'dispatch.json')['ticket_sha256'] == object_hash(ticket), 'Dispatched ticket bytes changed')
    observed = backend.inspect(ticket)
    identity_path = directory / 'identity.json'
    identity = read(identity_path) if identity_path.exists() else observed
    if not identity_path.exists():
        write_new(identity_path, observed)
    need(observed['invocation_id'] == identity['invocation_id'] and observed['boot_id'] == identity['boot_id'], 'Unit invocation/boot changed')
    if identity['main_pid'] and observed['main_pid']:
        need(identity['main_pid'] == observed['main_pid'] and
             (identity['starttime_ticks'] is None or identity['starttime_ticks'] == observed['starttime_ticks']), 'Main process identity changed')
    group_file = directory / 'cgroup.json'
    if observed['cgroup']:
        write_or_check(group_file, {'path': observed['cgroup']})
    groups = {observed['cgroup'], read(group_file)['path'] if group_file.exists() else ''} - {''}
    occupied = any(backend.populated(g) for g in groups)
    terminal = observed['sub'] in ('exited', 'failed', 'dead') and observed['active'] in ('active', 'failed', 'inactive')
    state = 'quiescent' if terminal and not occupied and observed['main_pid'] == 0 else 'running'
    # Result is deliberately not promoted to scientific completion.
    receipt = {'at_utc': stamp(), 'state': state, **observed}
    write_new(directory / 'observations' / (uuid.uuid4().hex + '.json'), receipt)
    return state, observed


def complete_marker(path):
    path = Path(path)
    need((path / 'COMPLETE.json').is_file() and not (path / 'FAILED.json').exists() and
         not any((path / name).exists() for name in PARTIALS), 'Missing/conflicting/partial terminal marker')
    return digest(path / 'COMPLETE.json')


def recheck_summary_history(summary, attempts_root, expected_paths):
    """Recheck all reader-bound history bytes, including failed predecessors."""
    root = Path(attempts_root).resolve()
    seen = set()
    for attempts in summary['attempts'].values():
        for observation in attempts:
            path = (root / observation['attempt']).resolve()
            need(path.is_relative_to(root) and path not in seen, 'Invalid or duplicated summary attempt identity')
            seen.add(path)
            names = sorted(str(p.relative_to(path)) for p in path.rglob('*') if p.is_file())
            need(names == observation['artifact_names'], 'Historical attempt inventory changed after final reader')
            for name, expected_hash in observation['input_hashes'].items():
                item = (path / name).resolve()
                need(item.is_relative_to(path) and digest(item) == expected_hash, 'Historical attempt bytes changed after final reader')
    need(seen == set(expected_paths), 'Final reader omitted an attempt history')


def review_retry(review, job, release, predecessor, prior_counter):
    root = Path(predecessor['out'])
    need(not (root / 'COMPLETE.json').exists() and not any((root / p).exists() for p in PARTIALS), 'Cannot retry complete/conflicting/partial predecessor')
    marker = 'FAILED.json' if (root / 'FAILED.json').is_file() else 'started.json'
    need((root / marker).is_file(), 'No valid predecessor start/failure receipt; no fabricated retry')
    normal = {'schema_version': 1, 'protocol_id': release.model['protocol_id'] if job['study'] == 'model' else release.source['protocol_id'],
              'protocol_sha256': release.hash_for(job['study'], 'protocol'), 'seed': job['seed']}
    if job['study'] == 'model':
        normal.update(feature_lock_sha256=release.hash_for('model', 'input'), vision=job['vision'], text=job['text'])
    else:
        normal.update(masks_sha256=release.hash_for('source', 'input'), mask=job['mask'])
    expected_keys = set(normal) | {'previous_attempt', 'previous_artifacts', 'reviewed', 'source_or_numerics_changed', 'reason_kind', 'reason'}
    need(set(review) == expected_keys and all(review[k] == v for k, v in normal.items()), 'Retry scientific binding differs')
    need(review['previous_attempt'] == f'attempt-{prior_counter:02d}' and review['previous_artifacts'] == {marker: digest(root / marker)}, 'Retry predecessor bytes differ')
    need(review['reviewed'] is True and review['source_or_numerics_changed'] is False and
         review['reason_kind'] in ('external_execution_failure', 'input_failure') and
         isinstance(review['reason'], str) and bool(review['reason'].strip()), 'Retry has not been explicitly reviewed')


def candidate_batch(jobs, states, resources):
    """Fixed-order admission only; no score- or size-based skipping."""
    if any(s in ('failed', 'ambiguous', 'running', 'quiescent', 'verifying') for s in states.values()):
        return []
    pending = [j for j in jobs if states[j['id']] == 'pending']
    if not pending:
        return []
    head = pending[0]
    need(all(states[j['id']] == 'complete' for j in jobs[:head['index']]), 'Schedule is not a completed prefix')
    # A batch never crosses replay/study boundaries. Full readers run quiescent.
    batch = [head]
    if resources['max_jobs'] == 2 and resources['classes'][head['id']] != 'exclusive' and len(pending) > 1:
        nxt = pending[1]
        if nxt['stage'] == head['stage'] and resources['classes'][nxt['id']] != 'exclusive':
            batch.append(nxt)
    return batch


class Controller:
    def __init__(self, release, backend):
        self.r, self.backend = release, backend
        self.root = release.root
        self.jobs = release.schedule['jobs']
        self.by_id = {j['id']: j for j in self.jobs}
        ensure_dir(self.root)
        write_or_check(self.root / 'execution.json', {'schema_version': 1, 'execution_sha256': release.sha,
                     'schedule_sha256': release.lock['files'][release.lock['schedule']], 'bindings_sha256': release.bindings_sha})
        for study in ('model', 'source'):
            absolute(release.bindings[study]['attempts_root']).mkdir(parents=True, exist_ok=True)

    def binding(self, study):
        snapshot = self.root / 'baseline-gate' / 'runner-bindings.json'
        return snapshot if study == 'model' and snapshot.exists() else Path(self.r.bindings[study]['runner_bindings'])

    def attempt_path(self, job, counter):
        cell = f"{job['vision']}--{job['text']}" if job['study'] == 'model' else job['mask']
        return absolute(self.r.bindings[job['study']]['attempts_root']) / cell / f"seed-{job['seed']}" / f'attempt-{counter:02d}'

    def directories(self, job):
        path = self.root / 'jobs' / job['id']
        values = sorted(path.iterdir()) if path.exists() else []
        need(all(p.is_dir() and p.name == f'attempt-{i+1:02d}' for i, p in enumerate(values)), 'Unknown/noncontiguous outer attempt tree')
        return values

    def spawn(self, directory, argv, extra):
        need(not directory.exists(), 'Outer ticket already exists')
        self.r.recheck()
        ensure_dir(directory)
        nonce = uuid.uuid4().hex
        ticket = {'schema_version': 1, 'execution_sha256': self.r.sha, 'bindings_sha256': self.r.bindings_sha,
                  'nonce': nonce, 'unit': f'rosetta-{self.r.sha[:12]}-{nonce}.service', 'argv': argv, 'cwd': str(self.r.cwd),
                  'environment_sha256': object_hash(self.r.lock['environment']),
                  'stdout': str(directory / 'stdout.log'), 'stderr': str(directory / 'stderr.log'), **extra}
        write_new(directory / 'ticket.json', ticket)
        write_new(directory / 'dispatch.json', {'ticket_sha256': object_hash(ticket), 'at_utc': stamp()})
        # A lost response is reconciled using this name; NEVER repeat this call.
        try:
            self.backend.launch(ticket)
        except Exception as error:
            write_new(directory / 'launch-error.json', {'at_utc': stamp(), 'exception_type': type(error).__name__})
            raise Blocked('Launch reply failed; reconcile retained unit, do not redispatch') from error
        return ticket

    def launch_job(self, job, counter=1, retry=None):
        out = self.attempt_path(job, counter)
        private = absolute(self.r.bindings[job['study']]['private_trace_root']) / job['id'] / f'attempt-{counter:02d}'
        need(not out.exists() and not private.exists(), 'Runner-owned directory is not fresh')
        if job['stage'] != 'replay':
            self.check_gate()
        if job['study'] == 'source':
            self.check_study_receipt('model')
        binding = self.binding(job['study'])
        args = ['--protocol', self.r.path_for(job['study'], 'protocol'), '--protocol-sha256', self.r.hash_for(job['study'], 'protocol'),
                '--feature-lock' if job['study'] == 'model' else '--masks', self.r.path_for(job['study'], 'input'),
                '--feature-lock-sha256' if job['study'] == 'model' else '--masks-sha256', self.r.hash_for(job['study'], 'input'),
                '--bindings', binding, '--out', out, '--private-log-dir', private, '--seed', job['seed']]
        args += ['--vision', job['vision'], '--text', job['text']] if job['study'] == 'model' else ['--mask', job['mask']]
        if retry:
            args += ['--retry-review', retry['path'], '--retry-review-sha256', retry['sha256']]
        directory = self.root / 'jobs' / job['id'] / f'attempt-{counter:02d}'
        self.spawn(directory, self.r.command(job['study'] + '_runner', args),
                   {'kind': 'fit', 'job': job['id'], 'index': job['index'], 'counter': counter, 'out': str(out),
                    'private_trace_dir': str(private), 'runner_bindings': str(binding), 'runner_bindings_sha256': digest(binding), 'retry': retry})

    def verify_binding(self, ticket):
        need(digest(ticket['runner_bindings']) == ticket['runner_bindings_sha256'], 'Runner binding snapshot changed')
        if ticket.get('retry'):
            need(digest(ticket['retry']['path']) == ticket['retry']['sha256'], 'Approved retry bytes changed')

    def inventory(self):
        known = set(self.by_id)
        root = self.root / 'jobs'
        need(not root.exists() or all(p.is_dir() and p.name in known for p in root.iterdir()), 'Unknown outer job')
        # Detect attempts the private controller did not launch, including empty
        # constructor remnants. Readers independently inventory the entire tree.
        for study in ('model', 'source'):
            expected = {self.attempt_path(j, i + 1).resolve() for j in self.jobs if j['study'] == study for i, _ in enumerate(self.directories(j))}
            cells = absolute(self.r.bindings[study]['attempts_root'])
            found = set()
            allowed_cells = {f"{j['vision']}--{j['text']}" if study == 'model' else j['mask'] for j in self.jobs if j['study'] == study}
            for cell in cells.iterdir():
                need(cell.is_dir() and cell.name in allowed_cells, 'Unknown entry inside cells')
                for seed in cell.iterdir():
                    need(seed.is_dir() and seed.name in {f'seed-{s}' for s in SEEDS}, 'Unknown entry inside seed tree')
                    for attempt in seed.iterdir():
                        need(attempt.is_dir(), 'Unknown entry inside attempt tree')
                        found.add(attempt.resolve())
            need(found <= expected, 'Untracked scientific attempt exists')
        return True

    def states(self):
        self.inventory()
        states = {}
        for job in self.jobs:
            dirs = self.directories(job)
            states[job['id']] = 'pending'
            # Reconcile every retained attempt, including failed predecessors.
            for directory in dirs:
                ticket = read(directory / 'ticket.json')
                need(ticket['job'] == job['id'] and ticket['counter'] == int(directory.name[-2:]) and ticket['execution_sha256'] == self.r.sha,
                     'Outer ticket scientific identity differs')
                self.verify_binding(ticket)
                service, _ = reconcile_service(directory, self.backend)
                state = service
                verified = directory / 'verified.json'
                if verified.exists():
                    record = read(verified)
                    need(service == 'quiescent', 'Previously verified writer is running')
                    need(digest(record['summary_path']) == record['summary_sha256'], 'Accepted reader bytes changed')
                    if record['status'] == 'complete':
                        need(complete_marker(ticket['out']) == record['complete_sha256'], 'Accepted completion changed')
                    state = record['status']
                states[job['id']] = state
        return states

    def reader_argv(self, study, binding, out):
        field = 'feature-lock' if study == 'model' else 'masks'
        return self.r.command(study + '_reader', ['--protocol', self.r.path_for(study, 'protocol'), '--protocol-sha256', self.r.hash_for(study, 'protocol'),
                    '--' + field, self.r.path_for(study, 'input'), '--' + field + '-sha256', self.r.hash_for(study, 'input'),
                    '--bindings', binding, '--out', out])

    def new_verification(self, study, targets, preflight=False, final_audit=False):
        base = self.root / 'verifications'
        counter = len(list(base.iterdir())) + 1 if base.exists() else 1
        directory = base / f'verify-{counter:04d}'
        binding_path = self.root / 'reader-bindings' / f'{counter:04d}.json'
        write_new(binding_path, {'runner_bindings': str(self.binding(study)), 'attempts_root': self.r.bindings[study]['attempts_root']})
        out = directory / 'summary.json'
        self.spawn(directory, self.reader_argv(study, binding_path, out), {'kind': 'verification', 'study': study, 'targets': targets,
                    'preflight': preflight, 'final_audit': final_audit, 'out': str(out), 'summary_bindings': str(binding_path), 'summary_bindings_sha256': digest(binding_path),
                    'runner_bindings': str(self.binding(study)), 'runner_bindings_sha256': digest(self.binding(study))})

    def accept_summary(self, ticket):
        out = Path(ticket['out'])
        need(out.is_file() and not Path(str(out) + '.partial').exists(), 'Reader output absent/partial')
        summary = read(out)
        study = ticket['study']; ih = summary['input_hashes']
        need(ih['protocol'] == self.r.hash_for(study, 'protocol') and ih['feature_lock' if study == 'model' else 'masks'] == self.r.hash_for(study, 'input'), 'Reader used other inputs')
        need(ih['summarizer'] == self.r.lock['files'][self.r.lock['code'][study + '_reader']] and
             ih['private_bindings'] == ticket['summary_bindings_sha256'] and ih['runner_bindings'] == ticket['runner_bindings_sha256'], 'Reader code/binding differs')
        need(not summary['inventory_findings'], 'Reader found invalid attempt inventory')
        need(digest(ticket['summary_bindings']) == ticket['summary_bindings_sha256'], 'Reader binding bytes changed')
        self.verify_binding(ticket)
        return summary

    def verification_tick(self):
        base = self.root / 'verifications'
        if not base.exists():
            return False
        for directory in sorted(base.iterdir()):
            need(directory.is_dir() and re.fullmatch(r'verify-\d{4}', directory.name), 'Unknown verifier record')
            ticket = read(directory / 'ticket.json')
            need(not ((directory / 'accepted.json').exists() and (directory / 'rejected.json').exists()), 'Conflicting verifier dispositions')
            if (directory / 'accepted.json').exists():
                state, _ = reconcile_service(directory, self.backend)
                need(state == 'quiescent', 'Accepted verifier is no longer quiescent')
                receipt = read(directory / 'accepted.json')
                need(digest(ticket['out']) == receipt['summary_sha256'], 'Accepted summary changed')
                if ticket['preflight']:
                    write_or_check(self.root / ('preflight-' + ticket['study'] + '.json'),
                                   {'summary_sha256': receipt['summary_sha256'], 'summary_path': ticket['out'],
                                    'verification': str(directory), 'ticket_sha256': object_hash(ticket)})
                elif ticket.get('final_audit') or not (self.root / (ticket['study'] + '-stage-complete.json')).exists():
                    summary = self.accept_summary(ticket)
                    self.publish_study_receipt(ticket, directory, summary)
                if ticket['study'] == 'model' and not ticket['preflight'] and not (self.root / 'baseline-gate' / 'gate.json').exists():
                    summary = self.accept_summary(ticket)
                    if summary['baseline_replay_gate']['status'] == 'satisfied' and self.reference_services_complete():
                        self.make_gate(summary, ticket['out'])
                continue
            if (directory / 'rejected.json').exists():
                raise Blocked('A strict verifier failed; preserve it for explicit resolution')
            service, observed = reconcile_service(directory, self.backend)
            if service == 'running':
                return True
            try:
                need(observed['result'] == 'success' and observed['exec_status'] == '0', 'Verifier service failed')
                summary = self.accept_summary(ticket)
                summary_sha = digest(ticket['out'])
                self.check_prior_acceptances(summary, ticket['study'])
                if ticket.get('final_audit'):
                    need(summary['status'] == 'complete', 'Final full-study summary is incomplete')
                for target in ticket['targets']:
                    job = self.by_id[target]
                    attempt_dir = self.directories(job)[-1]
                    fit_ticket = read(attempt_dir / 'ticket.json')
                    state, fit_service = reconcile_service(attempt_dir, self.backend)
                    need(state == 'quiescent', 'Fit is not quiescent during verification')
                    eligible = summary_job_complete(summary, job, fit_ticket['out'])
                    service_success = fit_service['result'] == 'success' and fit_service['exec_status'] == '0' and fit_service['exec_code'] == '1'
                    record = {'status': 'complete' if eligible and service_success else 'failed', 'artifact_eligible': eligible,
                              'service_success': service_success, 'service_result': fit_service['result'],
                              'exec_main_status': fit_service['exec_status'], 'exec_main_code': fit_service['exec_code'],
                              'summary_path': ticket['out'], 'summary_sha256': summary_sha,
                              'complete_sha256': complete_marker(fit_ticket['out']) if eligible else None}
                    write_or_check(attempt_dir / 'verified.json', record)
                self.r.recheck(); self.inventory()
                self.publish_study_receipt(ticket, directory, summary)
                if ticket['preflight']:
                    write_or_check(self.root / ('preflight-' + ticket['study'] + '.json'), {'summary_sha256': summary_sha, 'summary_path': ticket['out'],
                                   'verification': str(directory), 'ticket_sha256': object_hash(ticket)})
                if ticket['study'] == 'model' and summary['baseline_replay_gate']['status'] == 'satisfied' and self.reference_services_complete():
                    self.make_gate(summary, ticket['out'])
                # Final durable commit; preceding deterministic metadata can be
                # reconstructed after a controller interruption without a fit.
                write_or_check(directory / 'accepted.json', {'summary_sha256': summary_sha})
            except Exception as error:
                write_new(directory / 'rejected.json', {'exception_type': type(error).__name__, 'at_utc': stamp()})
                raise
        return False

    def check_prior_acceptances(self, summary, study):
        for job in self.jobs:
            if job['study'] != study:
                continue
            directories = self.directories(job)
            if not directories:
                continue
            directory = directories[-1]
            record = directory / 'verified.json'
            if record.exists() and read(record)['status'] == 'complete':
                fit = read(directory / 'ticket.json')
                need(summary_job_complete(summary, job, fit['out']), 'A previously accepted job became unavailable in the full reader')

    def publish_study_receipt(self, ticket, directory, summary):
        if ticket['preflight'] or summary['status'] != 'complete':
            return
        for job in self.jobs:
            if job['study'] == ticket['study']:
                directories = self.directories(job)
                if not directories or not (directories[-1] / 'verified.json').exists() or read(directories[-1] / 'verified.json')['status'] != 'complete':
                    return
        name = ('final-audit-' + ticket['study'] if ticket.get('final_audit') else ticket['study'] + '-stage-complete') + '.json'
        path = self.root / name
        receipt = {'summary_path': ticket['out'], 'summary_sha256': digest(ticket['out']),
                   'verification': str(directory), 'ticket_sha256': object_hash(ticket)}
        # First complete study summary is the stage gate. The final audit has
        # its own immutable receipt; no previous summary is replaced.
        if not path.exists():
            write_new(path, receipt)

    def check_study_receipt(self, study, final=False):
        path = self.root / (('final-audit-' + study if final else study + '-stage-complete') + '.json')
        receipt = read(path); directory = Path(receipt['verification'])
        need(directory.parent == self.root / 'verifications', 'Study receipt outside verifier tree')
        ticket = read(directory / 'ticket.json')
        need(ticket['study'] == study and object_hash(ticket) == receipt['ticket_sha256'] and
             bool(ticket.get('final_audit')) == final, 'Study gate ticket differs')
        need(digest(ticket['out']) == receipt['summary_sha256'] and
             read(directory / 'accepted.json')['summary_sha256'] == receipt['summary_sha256'], 'Study gate bytes differ')
        summary = self.accept_summary(ticket)
        need(summary['status'] == 'complete', 'Complete study gate references incomplete reader')
        self.check_prior_acceptances(summary, study)

    def final_artifact_check(self):
        for study in ('model', 'source'):
            receipt = read(self.root / ('final-audit-' + study + '.json'))
            need(digest(receipt['summary_path']) == receipt['summary_sha256'], 'Final reader output changed')
            summary = read(receipt['summary_path'])
            expected = {self.attempt_path(j, i + 1).resolve() for j in self.jobs if j['study'] == study for i, _ in enumerate(self.directories(j))}
            recheck_summary_history(summary, self.r.bindings[study]['attempts_root'], expected)
        for job in self.jobs:
            directory = self.directories(job)[-1]
            ticket = read(directory / 'ticket.json'); root = Path(ticket['out'])
            need(read(directory / 'verified.json')['status'] == 'complete', 'Final schedule includes unavailable job')
            complete_marker(root)
            manifest = read(root / 'COMPLETE.json')['files']
            actual = {str(p.relative_to(root)) for p in root.rglob('*') if p.is_file()} - {'COMPLETE.json'}
            need(actual == set(manifest), 'Final attempt artifact inventory changed')
            for name, expected in manifest.items():
                path = (root / name).resolve()
                need(path.is_relative_to(root.resolve()) and digest(path) == expected, 'Final accepted artifact bytes changed')
        self.r.recheck(); self.inventory()

    def reference_services_complete(self):
        for job in self.jobs[:5]:
            directories = self.directories(job)
            if not directories or not (directories[-1] / 'verified.json').exists() or read(directories[-1] / 'verified.json')['status'] != 'complete':
                return False
        return True

    def make_gate(self, summary, summary_path):
        path = self.root / 'baseline-gate' / 'gate.json'
        if path.exists():
            self.check_gate(); return
        entries = {}
        for job in self.jobs[:5]:
            dirs = self.directories(job)
            need(bool(dirs), 'Reference attempt missing')
            directory = dirs[-1]; ticket = read(directory / 'ticket.json')
            need(read(directory / 'verified.json')['status'] == 'complete' and summary_job_complete(summary, job, ticket['out']), 'Reference cell not complete')
            state, _ = reconcile_service(directory, self.backend)
            need(state == 'quiescent', 'Reference writer still active')
            entries[str(job['seed'])] = {'path': ticket['out'], 'complete_sha256': complete_marker(ticket['out'])}
        binding = read(self.r.bindings['model']['runner_bindings'])
        for seed, entry in entries.items():
            entry['original_result_sha256'] = digest(binding['baseline_results'][seed])
        binding['baseline_replays'] = {s: e['path'] for s, e in entries.items()}
        snapshot = self.root / 'baseline-gate' / 'runner-bindings.json'
        write_or_check(snapshot, binding)
        write_new(path, {'execution_sha256': self.r.sha, 'protocol_sha256': self.r.hash_for('model', 'protocol'),
                        'feature_lock_sha256': self.r.hash_for('model', 'input'), 'summary_path': summary_path,
                        'summary_sha256': digest(summary_path), 'runner_bindings_sha256': digest(snapshot), 'seeds': entries})

    def check_gate(self):
        gate = read(self.root / 'baseline-gate' / 'gate.json')
        need(gate['execution_sha256'] == self.r.sha and gate['protocol_sha256'] == self.r.hash_for('model', 'protocol') and
             gate['feature_lock_sha256'] == self.r.hash_for('model', 'input') and set(gate['seeds']) == set(map(str, SEEDS)), 'Replay gate binding differs')
        need(digest(self.root / 'baseline-gate' / 'runner-bindings.json') == gate['runner_bindings_sha256'] and
             digest(gate['summary_path']) == gate['summary_sha256'], 'Replay gate bytes changed')
        original = read(self.r.bindings['model']['runner_bindings'])
        for seed, entry in gate['seeds'].items():
            need(complete_marker(entry['path']) == entry['complete_sha256'] and digest(original['baseline_results'][seed]) == entry['original_result_sha256'], 'Replay gate input changed')

    def tick(self):
        self.r.recheck(); self.backend.gate()
        states = self.states()
        if 'running' in states.values():
            return self.progress(states)
        if self.verification_tick():
            return self.progress(states, 'verifying')
        states = self.states()
        quiescent = [j for j in self.jobs if states[j['id']] == 'quiescent']
        if quiescent:
            study = quiescent[0]['study']
            need(all(j['study'] == study for j in quiescent), 'Mixed-stage writers bypassed schedule')
            self.new_verification(study, [j['id'] for j in quiescent])
            return self.progress(states, 'verifying')
        if any(v in ('failed', 'ambiguous') for v in states.values()):
            return self.progress(states, 'blocked')
        # Full readers verify both finalized studies before the first fit. Their
        # incomplete scientific summaries are valid preflight results.
        for study in ('model', 'source'):
            if not (self.root / ('preflight-' + study + '.json')).exists():
                self.new_verification(study, [], preflight=True)
                return self.progress(states, 'preflight')
        self.check_preflights()
        if all(s == 'complete' for s in states.values()):
            for study in ('model', 'source'):
                if not (self.root / ('final-audit-' + study + '.json')).exists():
                    self.new_verification(study, [], final_audit=True)
                    return self.progress(states, 'final_verification')
                self.check_study_receipt(study, final=True)
            self.final_artifact_check()
            return self.progress(states, 'complete')
        for job in candidate_batch(self.jobs, states, self.r.resources):
            self.launch_job(job)
            states[job['id']] = 'running'
        return self.progress(states)

    def check_preflights(self):
        for study in ('model', 'source'):
            receipt = read(self.root / ('preflight-' + study + '.json'))
            directory = Path(receipt['verification'])
            need(directory.parent == self.root / 'verifications', 'Preflight verifier lies outside control root')
            ticket = read(directory / 'ticket.json')
            need(ticket['preflight'] is True and ticket['study'] == study and object_hash(ticket) == receipt['ticket_sha256'], 'Preflight ticket differs')
            need(read(directory / 'accepted.json')['summary_sha256'] == receipt['summary_sha256'] and
                 digest(ticket['out']) == receipt['summary_sha256'] and receipt['summary_path'] == ticket['out'], 'Preflight result differs')
            self.accept_summary(ticket)

    def retry(self, job_id, review_path, expected):
        self.r.recheck(); self.backend.gate()
        self.check_preflights()
        states = self.states()
        need(not any(s in ('running', 'quiescent', 'verifying') for s in states.values()), 'Owned work is not quiescent/verified')
        need(not self.verification_tick(), 'Verifier is still active')
        need(all(value == 'complete' for key, value in states.items() if self.by_id[key]['index'] < self.by_id[job_id]['index']), 'Retry cannot bypass earlier failure')
        job = self.by_id[job_id]; dirs = self.directories(job)
        need(states[job_id] == 'failed' and dirs and len(dirs) < 99, 'Only an observed failed attempt can be reviewed for retry')
        path = absolute(review_path)
        need(digest(path) == expected, 'Retry review hash differs')
        predecessor = read(dirs[-1] / 'ticket.json')
        review_retry(read(path), job, self.r, predecessor, len(dirs))
        self.launch_job(job, len(dirs) + 1, {'path': str(path), 'sha256': expected})
        states[job_id] = 'running'
        return self.progress(states)

    def progress(self, states, status=None):
        result = {'schema_version': 1, 'execution_sha256': self.r.sha, 'at_utc': stamp(),
                  'status': status or 'in_progress',
                  'counts': {state: list(states.values()).count(state) for state in sorted(set(states.values()))},
                  'jobs': [{'id': job['id'], 'state': states[job['id']], 'attempt_count': len(self.directories(job))} for job in self.jobs]}
        state_sha = object_hash({k: v for k, v in result.items() if k != 'at_utc'})
        path = self.root / 'progress' / (state_sha + '.json')
        if not path.exists():
            write_new(path, result)
        return result


def summary_job_complete(summary, job, out):
    relative = '/'.join(Path(out).parts[-3:])
    if job['study'] == 'source':
        obs = summary['observations'][job['key']]
        return obs['status'] == 'available' and obs['verified_complete_attempts'] == 1 and obs['selected_attempt'] == relative
    attempts = summary['attempts'][job['key']]
    fully = [a for a in attempts if a['terminal_marker'] == 'COMPLETE.json' and a['terminal_manifest_verified'] and
             not a['findings'] and all(m['eligible'] for m in a['methods'].values())]
    return len(fully) == 1 and fully[0]['attempt'] == relative and all(
        summary['observations'][job['key'] + '/' + m]['status'] == 'available' for m in METHODS)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['validate', 'tick', 'run', 'retry', 'schedule'])
    for name in ('lock', 'bindings', 'model-protocol', 'source-protocol', 'masks', 'out', 'retry-review'):
        parser.add_argument('--' + name, type=Path)
    for name in ('lock-sha256', 'bindings-sha256', 'job', 'retry-review-sha256'):
        parser.add_argument('--' + name)
    args = parser.parse_args()
    if args.action == 'schedule':
        write_new(args.out, derive_schedule(read(args.model_protocol), read(args.source_protocol), read(args.masks)))
        return
    r = Release(args.lock, args.lock_sha256, args.bindings, args.bindings_sha256)
    if args.action == 'validate':
        print(json.dumps({'status': 'release_validated', 'jobs': len(r.schedule['jobs']), 'dispatches': 0})); return
    last_progress = None
    while True:
        with controller_lock(r):
            controller = Controller(r, Systemd())
            try:
                result = controller.retry(args.job, args.retry_review, args.retry_review_sha256) if args.action == 'retry' else controller.tick()
            except Exception as error:
                # Diagnostic text remains private; never dispatch a replacement
                # to guess whether an earlier launch took place.
                write_new(r.root / 'findings' / (uuid.uuid4().hex + '.json'),
                          {'at_utc': stamp(), 'exception_type': type(error).__name__, 'message': str(error)})
                raise
            current_progress = object_hash({k: v for k, v in result.items() if k != 'at_utc'})
            if current_progress != last_progress:
                print(json.dumps(result, indent=2), flush=True)
                last_progress = current_progress
        if args.action != 'run' or result['status'] in ('complete', 'blocked'):
            return
        time.sleep(30)  # Polling only. Never a job timeout or retry timer.


if __name__ == '__main__':
    main()
